def build_mo_bytes(catalog: dict[str, str], lang: str) -> bytes:
    """Compile a dict of msgid -> msgstr into binary GNU gettext .mo format."""
    header = (
        "Project-Id-Version: Olokuti Digital MVP\n"
        "Content-Type: text/plain; charset=UTF-8\n"
        "Content-Transfer-Encoding: 8bit\n"
        f"Language: {lang}\n"
        "Plural-Forms: nplurals=2; plural=(n != 1);\n"
    )
    entries = [("", header)] + sorted((k, v) for k, v in catalog.items() if k and v)
    n = len(entries)
    ids_table = []
    strs_table = []
    ids_blob = bytearray()
    strs_blob = bytearray()

    for msgid, msgstr in entries:
        b_id = msgid.encode("utf-8")
        b_str = msgstr.encode("utf-8")
        ids_table.append((len(b_id), len(ids_blob)))
        ids_blob.extend(b_id + b"\x00")
        strs_table.append((len(b_str), len(strs_blob)))
        strs_blob.extend(b_str + b"\x00")

    header_size = 28
    orig_tab_offset = header_size
    trans_tab_offset = orig_tab_offset + n * 8
    ids_start = trans_tab_offset + n * 8
    strs_start = ids_start + len(ids_blob)

    out = bytearray()
    out.extend(
        struct.pack(
            "<Iiiiiii",
            0x950412DE,
            0,
            n,
            orig_tab_offset,
            trans_tab_offset,
            0,
            0,
        )
    )
    for length, rel_off in ids_table:
        out.extend(struct.pack("<ii", length, ids_start + rel_off))
    for length, rel_off in strs_table:
        out.extend(struct.pack("<ii", length, strs_start + rel_off))
    out.extend(ids_blob)
    out.extend(strs_blob)
    return bytes(out)


def build_po_text(catalog: dict[str, str], lang: str) -> str:
    lines = [
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: Olokuti Digital MVP\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        f'"Language: {lang}\\n"',
        '"Plural-Forms: nplurals=2; plural=(n != 1);\\n"',
        "",
    ]
    for msgid, msgstr in sorted(catalog.items()):
        esc_id = msgid.replace("\\", "\\\\").replace('"', '\\"')
        esc_str = msgstr.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'msgid "{esc_id}"')
        lines.append(f'msgstr "{esc_str}"')
        lines.append("")
    return "\n".join(lines)


class Command(BaseCommand):
    help = "Write .po and compile binary .mo translation catalogues for all configured locales."

    def handle(self, *args, **options):
        locale_root = Path(settings.BASE_DIR) / "locale"
        for lang, mapping in LOCALES.items():
            lc_dir = locale_root / lang / "LC_MESSAGES"
            lc_dir.mkdir(parents=True, exist_ok=True)
            po_path = lc_dir / "django.po"
            mo_path = lc_dir / "django.mo"
            po_path.write_text(build_po_text(mapping, lang), encoding="utf-8")
            mo_path.write_bytes(build_mo_bytes(mapping, lang))
            self.stdout.write(f"Compiled {lang}: {len(mapping)} strings -> {mo_path}")
        self.stdout.write(self.style.SUCCESS("All 10 locale catalogues compiled successfully."))

